import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { webcrypto } from 'node:crypto';
globalThis.crypto ??= webcrypto;
const memory = new Map();
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) };
const bundle = await build({ stdin: { contents: `export * from './src/utils/adaptiveTraining'; export * from './src/utils/aiRoutineImport'; export * from './src/utils/storage'; export * from './src/utils/backup'; export * from './src/utils/calculations'; export * from './src/utils/gymWorkout'; export * from './src/utils/routines'; export { EXERCISES_DATABASE } from './src/data/exercises';`, resolveDir: process.cwd() }, bundle: true, write: false, platform: 'node', format: 'esm' });
const api = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const draft = api.parseImportedWorkout(JSON.stringify({ title: 'Training', programId: 'block-1', programWeek: 2, trainingPhase: 'STRENGTH', sessionGoal: 'Quality', exercises: [{ exerciseId: 'bench-press', sets: [{ plannedWeight: 80, plannedReps: 8, targetRpe: 8, targetRestSeconds: 120, plannedSetType: 'TOP_SET' }, { weight: 75, reps: 8, setType: 'BACK_OFF' }] }] }), api.EXERCISES_DATABASE);
let session = api.sessionFromImportedWorkout(draft, api.EXERCISES_DATABASE);
const exerciseId = session.exercises[0].id;
const firstId = session.exercises[0].sets[0].id;
const nextId = session.exercises[0].sets[1].id;
assert.equal(session.programWeek, 2);
assert.equal(session.exercises[0].sets[0].rpe, null);
assert.equal(session.exercises[0].sets[0].targetRpe, 8);
session = api.startWorkoutSet(session, exerciseId, firstId, new Date('2026-10-31T01:00:00Z'));
assert.equal(session.exercises[0].sets[0].restSeconds, undefined);
const finished = api.completeWorkoutSet({ ...session.exercises[0].sets[0], rpe: 9 }, new Date('2026-10-31T01:00:30Z'));
assert.equal(finished.rpe, 9);
assert.equal(finished.targetRpe, 8);
assert.equal(api.actualRpe(finished), 9);
assert.equal(finished.failureType, 'UNKNOWN', 'RPE does not imply failure');
assert.deepEqual(api.completeWorkoutSet(finished), finished, 'repeat completion is idempotent');
assert.equal(api.completeWorkoutSet({ ...finished, completed: false, rpe: undefined }).rpe, null);
assert.equal(api.completeWorkoutSet({ ...finished, completed: false, provenance: 'legacy-unknown', rpe: 8 }).rpe, null, 'legacy imported target cannot become actual');
session.exercises[0].sets[0] = finished;
session.pausedSeconds = 20;
session = api.startWorkoutSet(session, exerciseId, nextId, new Date('2026-10-31T01:02:30Z'));
assert.equal(session.exercises[0].sets[1].restSeconds, 100, 'pause intervals excluded');
assert.equal(session.exercises[0].sets[1].restKind, 'between-sets');
api.saveActiveSession(session);
const recovered = api.loadActiveSession();
assert.deepEqual(recovered, JSON.parse(JSON.stringify(session)), 'timestamps and actual rest survive restart');
assert.deepEqual(api.parseBackup(JSON.stringify(api.createBackup())).activeSession, JSON.parse(JSON.stringify(session)));
const undone = api.undoWorkoutSet(finished);
assert.equal(undone.completed, false);
assert.equal(undone.completedAt, undefined);
assert.equal(undone.rpe, null);
assert.equal(undone.targetRpe, 8);
const redone = api.completeWorkoutSet(undone);
assert.equal(redone.id, finished.id, 'undo and completion preserve stable set identity');
const old = { ...session, exercises: [{ ...session.exercises[0], sets: [{ id: 'legacy', setNumber: 1, weight: 80, reps: 8, rpe: 8, completed: true }] }] };
const oldBytes = JSON.stringify(old);
const normalized = api.normalizeAdaptiveSession(old);
assert.equal(JSON.stringify(old), oldBytes);
assert.equal(normalized.exercises[0].sets[0].rpe, 8);
assert.equal(normalized.exercises[0].sets[0].provenance, 'legacy-unknown');
assert.equal(api.actualRpe(normalized.exercises[0].sets[0]), null);
assert.deepEqual(api.normalizeAdaptiveSession(normalized), normalized);
const warmups = [1, 2, 3].map(number => ({ ...finished, id: `warmup-${number}`, setType: 'WARMUP' }));
assert.equal([...warmups, finished].filter(api.isWorkingSet).length, 1);
assert.equal(api.isWorkingSet({ ...finished, setType: 'ACTIVATION' }), false);
assert.equal(api.isWorkingSet({ ...finished, setType: 'UNSPECIFIED' }), false);
assert.equal(api.getExerciseRecords(warmups).maxWeight, 0, 'warmups do not produce PRs');
const equipment = { ...session.exercises[0], equipmentType: 'smith', weightUnit: 'kg', sets: [finished] };
assert.equal(api.calculateSessionVolume({ ...session, exercises: [equipment] }), 640, 'no Smith bar is added');
assert.equal(api.calculateSessionVolume({ ...session, exercises: [{ ...equipment, equipmentType: 'dumbbell' }] }), 640, 'dumbbell weight is per hand');
const converted = api.convertExerciseSets(equipment, 'lbs');
assert.equal(converted[0].weight, api.convertWeight(80, 'kg', 'lbs'));
assert.equal(converted[0].plannedWeight, api.convertWeight(80, 'kg', 'lbs'));
const partner = { ...session.exercises[0], id: 'partner', groupId: 'superset', sets: [{ ...undone, id: 'partner-set', startedAt: undefined, completedAt: undefined }] };
const grouped = { ...session, pausedSeconds: 0, exercises: [{ ...equipment, groupId: 'superset' }, partner] };
const transition = api.startWorkoutSet(grouped, partner.id, 'partner-set', new Date('2026-10-31T01:00:45Z'));
assert.equal(transition.exercises[1].sets[0].restKind, 'transition');
assert.equal(transition.exercises[1].sets[0].restSeconds, 15);
assert.equal(transition.exercises[0].sets[0].completed, true);
assert.equal(transition.exercises[1].sets[0].completed, false, 'starting partner does not fabricate completion');
const recipe = api.recipeFromSession(session, 'Plan', 90);
const fromRecipe = api.sessionFromRoutine(recipe);
assert.equal(fromRecipe.exercises[0].sets[0].targetRpe, 8);
assert.equal(fromRecipe.exercises[0].sets[0].rpe, null);
assert.equal(api.validAdaptiveSet({ setType: 'invalid' }), false);
assert.equal(api.validAdaptiveSet({ targetRpe: 8.1 }), false);
assert.equal(api.validAdaptiveSet({ painFeedback: { location: 'elbow', intensity: 11 } }), false);
assert.equal(api.validAdaptiveSessionMetadata({ checkIn: { energy: 6 } }), false);
assert.equal(api.validAdaptiveSessionMetadata({ programWeek: 0 }), false);
assert.equal(api.validAdaptiveExerciseMetadata({ feedback: { painIntensity: 11 } }), false);
assert.equal(api.calculateSessionVolume({ ...session, exercises: [{ ...equipment, sets: [{ ...finished, dropSegments: [{ weight: 80, reps: 8 }, { weight: 60, reps: 5 }] }] }] }), 940);
console.log('PASS adaptive plan/actual separation, null feedback, typed sets, independent supersets, true rest, pause exclusion, recovery, backup, unit conventions, and routine compatibility');
