import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({entryPoints:['src/utils/gymWorkout.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const { applyGymMachineConfig, convertExerciseSets, findPreviousMachineExercise } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const item = {id:'row-1',exerciseId:'chest-press',machineConfigId:'gym-1:a',machineBrand:'Same brand',machineSetting:'Seat 3',weightUnit:'kg',sets:[{id:'set-1',weight:20,previousWeight:10,reps:8,completed:false}]};
const before = JSON.stringify(item);
const config = {id:'b',exerciseId:'chest-press',brand:'Same brand',weightUnit:'lbs'};
const switched = applyGymMachineConfig(item,config,'gym-1');
assert.equal(switched.machineConfigId,'gym-1:b');
assert.equal(switched.machineSetting,undefined);
assert.equal(switched.sets[0].weight,44);
assert.equal(switched.sets[0].previousWeight,22);
assert.equal(switched.sets[0].id,'set-1');
assert.equal(JSON.stringify(item),before);
const completed = {...item,sets:[{...item.sets[0],completed:true}]};
assert.strictEqual(applyGymMachineConfig(completed,config,'gym-1'),completed);
assert.equal(convertExerciseSets(switched,'kg')[0].weight,20);
const history=[{exercises:[item,switched]}];
assert.equal(findPreviousMachineExercise(history,item.exerciseId,'Same brand','gym-1:b'),switched);
assert.equal(findPreviousMachineExercise(history,item.exerciseId,'Same brand','gym-2:b'),undefined);
const legacy = {...item,machineConfigId:undefined,weightUnit:undefined};
assert.equal(convertExerciseSets(legacy,'lbs')[0].weight,44);
assert.equal(findPreviousMachineExercise([{exercises:[legacy]}],item.exerciseId,'Same brand'),legacy);
assert.equal(findPreviousMachineExercise([{exercises:[legacy]}],item.exerciseId,'Same brand','gym-1:a'),undefined);
console.log('PASS machine identity, kg/lbs copy and switch, legacy units, input preservation, completed-set protection and separate gym histories');
