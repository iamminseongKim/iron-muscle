import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { build } from 'esbuild';
globalThis.crypto ??= webcrypto;
const bundle = await build({ entryPoints: ['src/utils/quickSets.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { buildQuickSets, applyQuickSets } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const plan = { mode: 'same', count: 3, weight: 60, reps: 10, rpe: 8, tempo: { eccentric: 3, pause: 0, concentric: 1 }, backoffWeight: 50, backoffReps: 12, backoffRpe: 7, weightStep: 5, repsStep: -2 };
assert.deepEqual(buildQuickSets(plan).map(s => [s.weight, s.reps, s.rpe]), [[60,10,8],[60,10,8],[60,10,8]]);
assert.deepEqual(buildQuickSets({ ...plan, mode: 'top' }).map(s => [s.weight, s.reps, s.rpe, s.tags[0]]), [[60,10,8,'탑세트'],[50,12,7,'백오프'],[50,12,7,'백오프']]);
assert.deepEqual(buildQuickSets({ ...plan, mode: 'pyramid' }).map(s => [s.weight,s.reps]), [[60,10],[65,8],[70,6]]);
assert.deepEqual(buildQuickSets({ ...plan, mode: 'pyramid', weightStep: -5, repsStep: 2 }).map(s => [s.weight,s.reps]), [[60,10],[55,12],[50,14]]);
const done = { id: 'done', setNumber: 1, completed: true, weight: 80, reps: 5, rpe: 9, comment: '완료' };
const pending = { id: 'pending', setNumber: 2, completed: false, weight: 40, reps: 12, side: 'right', comment: '보존', tags: ['스트랩 착용','백오프'], restSeconds: 90, previousWeight: 35 };
const original = [done,pending];
const snapshot = JSON.stringify(original);
const applied = applyQuickSets(original, plan, 'left');
assert.equal(JSON.stringify(original), snapshot);
assert.equal(applied[0], done);
assert.equal(applied[1].id, pending.id);
assert.equal(applied[1].comment, '보존');
assert.equal(applied[1].side, 'right');
assert.equal(applied[1].restSeconds, 90);
assert.equal(applied[1].previousWeight, 35);
assert.deepEqual(applied[1].tags, ['스트랩 착용']);
assert.equal(applied[2].side, 'left');
assert.equal(applied[2].completed, false);
assert.equal(new Set(applied.map(s => s.id)).size, 4);
assert.deepEqual(applied.map(s => s.setNumber), [1,2,3,4]);
assert.equal(applyQuickSets(applied, { ...plan,count: 1 })[3], applied[3]);
assert.equal(applyQuickSets(applied, { ...plan,rpe: undefined,tempo: undefined })[1].rpe, undefined);
assert.equal(applyQuickSets(applied, { ...plan,rpe: undefined,tempo: undefined })[1].tempo, undefined);
for (const patch of [{ count: 0 }, { count: 21 }, { count: 1.5 }, { weight: NaN }, { weight: -1 }, { reps: 1.5 }, { rpe: 8.2 }, { tempo: { eccentric: NaN, pause: 0, concentric: 1 } }, { mode: 'pyramid', repsStep: -5 }]) assert.throws(() => buildQuickSets({ ...plan,...patch }));
assert.equal(buildQuickSets({ ...plan,weight: 0 })[0].weight, 0);
console.log('PASS: quick set patterns, validation, completed records, metadata, unique IDs, sides and non-destructive application');
