import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--no-sandbox'] });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewport({ width: 390, height: 900, isMobile: true, hasTouch: true });
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:3000');
  await page.evaluate(() => {
    localStorage.clear(); localStorage.setItem('iron_language', 'ko');
    const exercise = (id, exerciseId, groupId) => ({ id, exerciseId, equipmentType: 'barbell', groupId, groupType: groupId ? 'superset' : undefined, sets: [{ id: `set-${id}`, setNumber: 1, weight: 20, reps: 10, completed: false, provenance: 'recorded', rpe: null, setType: 'UNSPECIFIED' }] });
    localStorage.setItem('iron_active_session_v1', JSON.stringify({ id: 'drag-ui', title: 'Manual workout', date: '2026-10-31', startTime: new Date().toISOString(), durationSeconds: 0, completed: false, exercises: [exercise('one', 'bench-press'), exercise('two', 'barbell-squat', 'pair'), exercise('three', 'lat-pulldown', 'pair')] }));
  });
  await page.reload({ waitUntil: 'networkidle2' });
  const order = () => page.$$eval('[data-workout-exercise]', cards => cards.map(card => card.dataset.workoutExercise));
  const title = id => page.$(`[data-workout-exercise="${id}"] h3 button`);
  let start = await (await title('one')).boundingBox();
  await page.mouse.move(start.x + 45, start.y + start.height / 2); await page.mouse.down();
  await wait(520);
  await page.waitForSelector('[data-dragging=true]');
  let target = await page.$eval('[data-workout-exercise="three"]', card => { const box = card.getBoundingClientRect(); return { x: box.x + 80, y: box.bottom - 8 }; });
  await page.mouse.move(target.x, target.y, { steps: 12 }); await page.mouse.up();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('iron_active_session_v1')).exercises[0].id === 'two');
  await page.waitForFunction(() => document.querySelector('[data-workout-exercise]')?.getAttribute('data-workout-exercise') === 'two');
  assert.deepEqual(await order(), ['two', 'three', 'one'], 'group stays intact when moving past it');
  await page.reload({ waitUntil: 'networkidle2' });
  assert.deepEqual(await order(), ['two', 'three', 'one'], 'order recovered');
  const cdp = await page.target().createCDPSession();
  start = await (await title('one')).boundingBox();
  await page.evaluate(() => document.querySelector('[data-workout-exercise="one"]').scrollIntoView({ block: 'center' }));
  start = await (await title('one')).boundingBox();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: start.x + 60, y: start.y + start.height / 2 }] });
  await wait(520);
  await page.waitForSelector('[data-dragging=true]');
  target = await page.$eval('[data-workout-exercise="two"]', card => { const box = card.getBoundingClientRect(); return { x: box.x + 80, y: box.top + 8 }; });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [target] });
  await wait(100);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('iron_active_session_v1')).exercises[0].id === 'one');
  await page.waitForFunction(() => document.querySelector('[data-workout-exercise]')?.getAttribute('data-workout-exercise') === 'one');
  assert.deepEqual(await order(), ['one', 'two', 'three'], 'touch hold and drag works');
  await wait(750);
  await page.evaluate(() => document.querySelector('[data-workout-exercise="three"]').scrollIntoView({ block: 'center' }));
  start = await (await title('three')).boundingBox();
  await page.mouse.move(start.x + 60, start.y + 14); await page.mouse.down(); await wait(520);
  await page.waitForSelector('[data-dragging=true]');
  target = await page.$eval('[data-workout-exercise="one"]', card => { const box = card.getBoundingClientRect(); return { x: box.x + 80, y: box.top + 8 }; });
  await page.mouse.move(target.x, target.y, { steps: 12 }); await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('[data-workout-exercise]')?.getAttribute('data-workout-exercise') === 'two');
  assert.deepEqual(await order(), ['two', 'three', 'one'], 'dragging a group member moves the whole group');
  await wait(750);
  await page.evaluate(() => document.querySelector('[data-workout-exercise="one"]').scrollIntoView({ block: 'center' }));
  start = await (await title('one')).boundingBox();
  await page.mouse.move(start.x + 60, start.y + 14); await page.mouse.down(); await wait(520);
  await page.waitForSelector('[data-dragging=true]');
  target = await page.$eval('[data-workout-exercise="two"]', card => { const box = card.getBoundingClientRect(); return { x: box.x + 80, y: box.top + 8 }; });
  await page.mouse.move(target.x, target.y, { steps: 12 }); await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('[data-workout-exercise]')?.getAttribute('data-workout-exercise') === 'one');
  await wait(750);
  const input = await page.$('[data-workout-exercise="one"] input[aria-label="1세트 무게"]');
  await input.hover(); await page.mouse.down(); await wait(520);
  assert.equal(await page.$('[data-dragging=true]'), null, 'inputs never initiate a drag');
  await page.mouse.up();
  assert.ok(!(await page.$eval('[data-workout-exercise="one"]', card => card.textContent)).includes('목표 RPE'), 'manual rows do not show nonexistent targets');
  await page.evaluate(() => document.querySelector('[data-workout-exercise="one"]').scrollIntoView({ block: 'center' }));
  start = await (await title('one')).boundingBox();
  const beforeScroll = await order();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: start.x + 60, y: start.y + 14 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x + 60, y: start.y - 60 }] });
  await wait(520);
  assert.equal(await page.$('[data-dragging=true]'), null, 'a swipe before the hold threshold scrolls without dragging');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.deepEqual(await order(), beforeScroll);
  await page.evaluate(() => document.querySelector('[data-workout-exercise="one"]').scrollIntoView({ block: 'center' }));
  start = await (await title('one')).boundingBox();
  await page.mouse.move(start.x + 60, start.y + 14); await page.mouse.down(); await wait(520);
  await page.waitForSelector('[data-dragging=true]');
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.equal(await page.$('[data-dragging=true]'), null, 'escape cancels without saving');
  assert.deepEqual(await order(), beforeScroll);
  await wait(750);

  await page.click('[data-workout-exercise="one"] button[aria-label="1세트 시작"]');
  await page.click('[data-workout-exercise="one"] button[aria-label="1세트 완료"]');
  await page.waitForSelector('[role=dialog][aria-label="세트 피드백"]');
  const feedback = await page.$eval('[aria-label="세트 피드백"]', node => node.textContent);
  assert.ok(feedback.includes('체감 강도 (RPE)') && !feedback.includes('목표 RPE'), 'manual feedback uses neutral language');
  assert.deepEqual(errors, []);
  console.log('PASS mouse and touch long-press reorder, grouped blocks, recovery, interactive input exclusion and manual workout copy');
} finally { await browser.close(); }
