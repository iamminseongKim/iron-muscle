import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { webcrypto } from 'node:crypto';
globalThis.crypto ??= webcrypto;
const bundle = await build({ entryPoints: ['src/utils/workoutFlow.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { repeatWorkout, getExerciseMoveAvailability, moveWorkoutExercise, workoutSummary } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const set = (id, extra = {}) => ({ id, setNumber: 1, weight: 50, reps: 10, completed: true, rpe: 9, comment: 'private', restSeconds: 120, tags: ['웜업', '실패지점'], plannedRestSeconds: 90, tempo: { eccentric: 2, pause: 0, concentric: 1 }, ...extra });
const exercise = (id, extra = {}) => ({ id, exerciseId: 'custom-press', exerciseName: 'Personal exercise', equipmentType: 'machine', weightUnit: 'kg', machineBrand: 'User brand', machineConfigId: 'gym-1:machine-1', machineSetting: 'Seat 3', executionMode: 'unilateral', notes: 'private', sets: [set(`set-${id}`)], ...extra });
const source = { id: 'source', title: 'Chest day', date: '2026-10-20', startTime: '2026-10-20T10:00:00Z', endTime: '2026-10-20T11:00:00Z', durationSeconds: 3600, completed: true, weightUnit: 'lbs', bodyWeight: 80, notes: 'private', overallRpe: 9, conditionEmoji: '🔥', isDeload: true, targetCategories: ['chest'], targetPartIds: ['chest'], exercises: [exercise('a', { groupId: 'old-group', groupType: 'superset', groupLabel: 'A-1' }), exercise('b', { groupId: 'old-group', groupType: 'superset', groupLabel: 'A-2', weightUnit: undefined, sets: [set('assisted', { weight: -30 }), set('skipped', { completed: false })] }), exercise('untouched', { sets: [set('uncompleted', { completed: false })] })] };
const snapshot = JSON.stringify(source);
const result = repeatWorkout(source, { now: new Date(2026, 9, 27, 12), bodyWeight: 75 });
assert.equal(result.date, '2026-10-27');
assert.equal(result.completed, false);
assert.equal(result.durationSeconds, 0);
assert.equal(result.exercises.length, 2);
assert.equal(result.exercises[1].weightUnit, 'lbs');
assert.equal(result.bodyWeight, 75);
assert.equal(result.endTime, undefined);
assert.equal(result.overallRpe, undefined);
assert.equal(result.notes, undefined);
assert.equal(result.isDeload, false);
assert.equal(result.exercises[0].machineConfigId, source.exercises[0].machineConfigId);
assert.equal(result.exercises[0].exerciseId, source.exercises[0].exerciseId);
assert.equal(result.exercises[0].notes, undefined);
assert.equal(result.exercises[0].groupId, result.exercises[1].groupId);
assert.notEqual(result.exercises[0].groupId, 'old-group');
assert.equal(result.exercises[0].groupLabel, 'A-1');
assert.equal(result.exercises[1].sets[0].weight, -30);
for (const ex of result.exercises) for (const s of ex.sets) {
  assert.equal(s.completed, false);
  assert.equal(s.previousWeight, s.weight);
  assert.equal(s.previousReps, s.reps);
  assert.equal(s.rpe, undefined);
  assert.equal(s.restSeconds, undefined);
  assert.equal(s.comment, undefined);
  assert.deepEqual(s.tags, ['웜업']);
  assert.equal(s.plannedRestSeconds, 90);
  assert.deepEqual(s.tempo, { eccentric: 2, pause: 0, concentric: 1 });
}
const sourceIds = new Set([source.id, ...source.exercises.flatMap(ex => [ex.id, ...ex.sets.map(s => s.id)])]);
const newIds = [result.id, ...result.exercises.flatMap(ex => [ex.id, ...ex.sets.map(s => s.id)])];
assert.equal(new Set(newIds).size, newIds.length);
assert.ok(newIds.every(id => !sourceIds.has(id)));
result.exercises[0].sets[0].tempo.eccentric = 5;
result.targetPartIds.push('back');
assert.equal(JSON.stringify(source), snapshot);
assert.equal(repeatWorkout(source).bodyWeight, undefined);
const singlePartnerSource = { ...source, exercises: [source.exercises[0], { ...source.exercises[1], sets: [set('skipped-partner', { completed: false })] }] };
const singlePartnerSnapshot = JSON.stringify(singlePartnerSource);
const singlePartner = repeatWorkout(singlePartnerSource);
assert.equal(singlePartner.exercises.length, 1);
for (const field of ['groupId', 'groupType', 'groupLabel', 'groupColor']) assert.equal(singlePartner.exercises[0][field], undefined);
assert.equal(JSON.stringify(singlePartnerSource), singlePartnerSnapshot);

assert.throws(() => repeatWorkout({ ...source, completed: false }));
assert.throws(() => repeatWorkout({ ...source, exercises: [] }));
assert.throws(() => repeatWorkout({ ...source, exercises: [exercise('zero', { sets: [set('zero', { reps: 0 })] })] }));

const a = exercise('a'), b = exercise('b', { groupId: 'g', groupLabel: 'A-1' }), c = exercise('c', { groupId: 'g', groupLabel: 'A-2' }), d = exercise('d');
const list = [a, b, c, d];
const listBefore = JSON.stringify(list);
assert.deepEqual(getExerciseMoveAvailability(list, 'a'), { up: false, down: true });
assert.deepEqual(getExerciseMoveAvailability(list, 'b'), { up: true, down: true });
assert.deepEqual(getExerciseMoveAvailability(list, 'missing'), { up: false, down: false });
assert.deepEqual(moveWorkoutExercise(list, 'c', 'up').map(ex => ex.id), ['b', 'c', 'a', 'd']);
assert.deepEqual(moveWorkoutExercise(list, 'b', 'down').map(ex => ex.id), ['a', 'd', 'b', 'c']);
assert.deepEqual(moveWorkoutExercise(list, 'a', 'up'), list);
assert.deepEqual(moveWorkoutExercise(list, 'missing', 'down'), list);
assert.deepEqual(moveWorkoutExercise([a, b, d, c], 'b', 'up').map(ex => ex.id), ['b', 'c', 'a', 'd']);
assert.equal(JSON.stringify(list), listBefore);
assert.strictEqual(moveWorkoutExercise(list, 'a', 'down')[2], a);

const makeSession = (id, date, extra = {}) => ({ ...source, id, date, startTime: `${date}T10:00:00Z`, exercises: [exercise('summary')], ...extra });
const old = makeSession('old', '2026-10-18');
const recent = makeSession('recent', '2026-10-20');
const current = makeSession('current', '2026-10-27', { exercises: [exercise('summary', { sets: [set('summary', { weight: 60, reps: 12 })] })] });
const future = makeSession('future', '2026-10-28');
const otherGym = makeSession('other-gym', '2026-10-26', { exercises: [exercise('summary', { machineConfigId: 'gym-2:machine-1' })] });
const uncompleted = makeSession('uncompleted', '2026-10-26', { completed: false });
const history = [recent, old, current, future, otherGym, uncompleted];
const historyBefore = JSON.stringify(history);
const summary = workoutSummary(current, history);
assert.equal(summary.previous.id, 'recent');
assert.equal(summary.completedSets, 1);
assert.equal(summary.reps, 12);
assert.equal(summary.volume, 720);
assert.equal(summary.volumeDelta, 220);
assert.equal(summary.repDelta, 2);
assert.equal(summary.setDelta, 0);
assert.equal(summary.personalBests.length, 1);
assert.equal(summary.personalBests[0].weight, 60);
assert.equal(summary.personalBests[0].unit, 'kg');
assert.equal(JSON.stringify(history), historyBefore);
const lbs = makeSession('pounds', '2026-10-26', { exercises: [exercise('summary', { weightUnit: 'lbs', sets: [set('pounds', { weight: 110.231 })] })] });
assert.equal(workoutSummary(current, [lbs]).volumeDelta, 220);
assert.equal(workoutSummary(current, []).previous, null);
assert.deepEqual(workoutSummary(current, []).personalBests, []);
assert.deepEqual(workoutSummary(makeSession('bodyweight', '2026-10-27', {exercises: [exercise('body', {equipmentType: 'bodyweight'})]}), history).personalBests, []);
assert.deepEqual(workoutSummary(makeSession('assisted', '2026-10-27', {exercises: [exercise('assist', {sets: [set('negative', {weight: -20})]})]}), history).personalBests, []);
assert.equal(workoutSummary(current, []).volumeDelta, null);
assert.equal(workoutSummary(makeSession('empty', '2026-10-27', { exercises: [] }), history).previous, null);
const sameDayEarlier = makeSession('earlier', '2026-10-27', { startTime: '2026-10-27T09:00:00Z' });
assert.equal(workoutSummary(current, [recent, sameDayEarlier]).previous.id, 'earlier');
assert.equal(workoutSummary(current, [makeSession('different-seat', '2026-10-26', { exercises: [exercise('summary', { machineSetting: 'Seat 4' })] })]).previous, null);
const reorderedPrior = makeSession('prior-order', '2026-10-26', {exercises: [exercise('second', {exerciseId: 'custom-row'}), exercise('first')]});
const reorderedCurrent = makeSession('current-order', '2026-10-27', {exercises: [exercise('first'), exercise('second', {exerciseId: 'custom-row'})]});
assert.equal(workoutSummary(reorderedCurrent, [reorderedPrior]).previous.id, 'prior-order');
assert.deepEqual(workoutSummary(current, [future, otherGym]).personalBests, []);
assert.deepEqual(workoutSummary(makeSession('equal', '2026-10-27'), [lbs]).personalBests, []);
