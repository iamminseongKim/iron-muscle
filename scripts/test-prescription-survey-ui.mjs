  await page.evaluate(() => [...document.querySelectorAll('button')].find(node => node.textContent.startsWith('휴식 타이머 닫기'))?.click());
  const editSecond = await page.$('[data-workout-set="changed"]');
  await editSecond.evaluate(node => [...node.querySelectorAll('button')].find(button => button.textContent.trim() === '기록 수정').click());
