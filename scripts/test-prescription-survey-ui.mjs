  assert.deepEqual(await values(), [29.5, 0, 0]);
  await click('목표 템포로 복원');
  assert.deepEqual(await values(), [30, 0, 0]);
  assert.equal((await active()).exercises[0].sets[2].tempoSource, undefined);
  await page.setViewport({ width: 320, height: 640, isMobile: true, hasTouch: true });
  assert.ok(await page.$eval('[role="dialog"][aria-label="세트 피드백"]', node => node.scrollWidth <= node.clientWidth));
