import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ stdin: { contents: "export * from './src/utils/adaptiveAnalysis'; export * from './src/utils/aiPromptGenerator';", resolveDir: process.cwd() }, bundle: true, write: false, platform: 'node', format: 'esm' });
const api = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const set = (extra = {}) => ({ id: 'set', setNumber: 1, completed: true, weight: 80, reps: 8, plannedWeight: 80, plannedReps: 8, targetRpe: 8, rpe: 9.5, provenance: 'recorded', setType: 'WORKING', plannedRestSeconds: 120, restSeconds: 90, startedAt: '2026-10-31T00:02:00Z', completedAt: '2026-10-31T00:02:30Z', ...extra });
const exercise = (sets = [set()], extra = {}) => ({ id: 'exercise', exerciseId: 'bench-press', equipmentType: 'barbell', weightUnit: 'kg', sets, ...extra });
const session = (exercises = [exercise()], extra = {}) => ({ id: 'session', title: 'Adaptive', date: '2026-10-31', startTime: '2026-10-31T00:00:00Z', completed: true, durationSeconds: 3600, exercises, ...extra });
const sample = session([exercise([set({ id: 'warmup', setType: 'WARMUP', weight: 20 }), set({ id: 'activation', setType: 'ACTIVATION', weight: 20 }), set(), set({ id: 'missing', setType: 'UNSPECIFIED', rpe: null }), set({ id: 'pending', completed: false, weight: 999, reps: 99 })])]);
const summary = api.summarizeAdaptiveSession(sample);
assert.equal(summary.totalSets, 4);
assert.equal(summary.workingSets, 1);
assert.equal(summary.warmupSets, 1);
assert.equal(summary.activationSets, 1);
assert.equal(summary.unspecifiedSets, 1);
assert.equal(summary.workingVolume, 640);
assert.equal(summary.maxRpe, 9.5);
assert.equal(summary.failureSets, 0, 'high RPE is not failure');
assert.equal(api.summarizeAdaptiveSession(session([exercise([set({ provenance: 'legacy-unknown', rpe: 8 })])])).averageRpe, null);
const drop = api.summarizeAdaptiveSession(session([exercise([set({ setType: 'DROP_SET', dropSegments: [{ weight: 80, reps: 4 }, { weight: 60, reps: 4 }] })])]));
assert.equal(drop.totalVolume, 560);
assert.equal(drop.totalReps, 8);
const nextSet = set({ id: 'next', completed: false });
const suggestion = api.suggestNextSet({ exercise: exercise(), completedSet: set(), nextSet });
assert.equal(suggestion.direction, 'decrease');
assert.equal(suggestion.weight, 77.5);
assert.equal(nextSet.weight, 80, 'proposal does not mutate next prescription');
for (const completedSet of [set({ rpe: null }), set({ targetRpe: undefined }), set({ setType: 'WARMUP' }), set({ provenance: 'legacy-unknown' })]) assert.equal(api.suggestNextSet({ exercise: exercise(), completedSet, nextSet }), null);
assert.equal(api.suggestNextSet({ exercise: exercise([set({ painFeedback: { location: 'elbow', intensity: 2 } })]), completedSet: set(), nextSet }), null);
assert.equal(api.suggestNextSet({ exercise: exercise(), completedSet: set({ rpe: 6 }), nextSet, phase: 'DELOAD' }), null);
assert.equal(api.suggestNextSet({ exercise: exercise(), completedSet: set({ rpe: 6 }), nextSet, pain: true }), null);
const history = [session([exercise([set({ weight: 70, rpe: 8 })])], { id: 'old', date: '2026-10-30', startTime: '2026-10-30T00:00:00Z' })];
const comparison = api.compareExercise(exercise(), session(), history).comparison;
assert.equal(comparison.weightDeltaKg, 10);
assert.equal(comparison.rpeDelta, 1.5);
assert.equal(api.compareExercise(exercise([set()], { equipmentType: 'machine' }), session(), history).comparison, null);
const before = JSON.stringify(sample);
for (const language of ['ko','en','ja','zh-CN','zh-TW','es','fr','de']) {
 const md = api.generateAiCoachingMarkdown([sample], { language, scope: 'all', selectedDate: '2026-10-31' });
 assert.ok(md.includes('v3.0'));
 assert.ok(md.includes('80 kg'));
 assert.ok(!md.includes('999 kg'), 'pending draft is not exported as actual');
 assert.ok(md.includes('9.5'));
 assert.ok(md.includes('RPE 8 /') || md.includes('RPE 8 /'));
 if (language !== 'ko') assert.ok(!/[가-힣]/.test(md), language);
}
assert.equal(JSON.stringify(sample), before);
const md = api.generateAiCoachingMarkdown([session([exercise([set({ rpe: null, provenance: 'legacy-unknown' })])], { checkIn: { notes: 'Cold | morning\nKeep', energy: 1 }, trainingPhase: 'RECOVERY' })], { language: 'en', scope: 'day', selectedDate: '2026-10-31' });
assert.ok(md.includes('Legacy source unknown'));
assert.ok(md.includes('Cold \\| morning<br>Keep'));
assert.ok(md.includes('Low readiness recorded'));
assert.ok(md.includes('Recovery'));
assert.ok(md.includes('Do not diagnose overtraining from one session'));
assert.ok(!md.includes('following 4'));
const dayWithHistory = api.generateAiCoachingMarkdown([session()], { language: 'en', scope: 'day', selectedDate: '2026-10-31' }, history);
assert.ok(dayWithHistory.includes('Previous performance · 2026-10-30'));
assert.ok(!dayWithHistory.includes('## 2026-10-30'), 'prior history supports comparison without exporting unrelated sessions');
console.log('PASS adaptive working-set summaries, nullable provenance, drop segments, pain and RPE gates, approval-only suggestions, comparable history and eight-language actual-only exports');
